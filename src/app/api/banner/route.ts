import { NextResponse } from "next/server";
import { generate, LlmUnavailable } from "@/lib/llm";
import { ArtDirectionSchema, BannerEditSchema, BannersRewriteSchema, type Concept } from "@/lib/schemas";
import { BANNER_EDIT_SYSTEM, bannerEditUser, BANNERS_REWRITE_SYSTEM, bannersRewriteUser } from "@/lib/prompts";
import { campaignPayload, getCurrent, setCurrent, type BannerSnapshot, type StoredCampaign } from "@/lib/campaign-store";
import { ASPECTS, editImage, generateImage, hasImage, visualKeyFor } from "@/lib/visuals";
import { loadStudioSkill } from "@/lib/studio-skill";

/**
 * POST { action: "edit", conceptId, instruction, live? }  one banner, as asked: its words, its photo (edited in place), or both
 * POST { action: "rewrite", instructions }               every banner follows the instructions (new photos are generated by the page)
 * POST { action: "undo", conceptId }                     back to that banner's previous version
 * POST { action: "art-direction" }                       the campaign's shared look in one line, for the instructions box
 *                                                        (instructions from the Creative Studio skill's "Art direction" section)
 * Returns the Studio payload ({ current, visuals }) plus { summary, changed }.
 */
type Body =
  | { action: "edit"; conceptId: string; instruction: string; live?: boolean }
  | { action: "rewrite"; instructions: string }
  | { action: "undo"; conceptId: string }
  | { action: "art-direction" };

const REPLACED = "A new campaign was written meanwhile, so this change was dropped.";

/**
 * Describes the look the campaign's pictures already share and stores it as the applied instructions,
 * so the box shows what the pictures follow, and "Generate visuals" only rewrites once the user changes it.
 */
async function artDirection(cur: StoredCampaign) {
  const skill = loadStudioSkill();
  const r = await generate({
    kind: "art-direction",
    schema: ArtDirectionSchema,
    system: skill.artDirection,
    user: `CAMPAIGN: ${cur.campaign.name}\nAUDIENCE: ${cur.campaign.brief.audience}\n\nPHOTO DESCRIPTIONS:\n${cur.campaign.concepts
      .map((c, i) => `${i + 1}. ${c.visualPrompt}`)
      .join("\n")}`,
    maxTokens: 2000,
  });
  const direction = r.data.direction.trim();
  const latest = getCurrent()!;
  if (latest.id !== cur.id) throw new Error(REPLACED);
  setCurrent({ ...latest, bannerInstructions: direction });
  return { summary: direction, changed: { words: false, picture: false } };
}

const overridesOf = (cur: StoredCampaign, id: string) =>
  Object.fromEntries(ASPECTS.flatMap((a) => (cur.visualKeys?.[`${id}:${a}`] ? [[`${id}:${a}`, cur.visualKeys[`${id}:${a}`]]] : [])));

const wordsChanged = (a: Concept, b: Concept) => a.headline !== b.headline || a.subline !== b.subline || a.cta !== b.cta;

/**
 * Writes new versions of some banners. Re-reads the store first, so an edit that took a minute (photos)
 * doesn't undo a parallel edit of another banner. `next` maps concept id -> new concept and its photo overrides.
 */
function saveBanners(campaignId: string, next: Map<string, BannerSnapshot>, opts: { history: "push" | "pop"; extra?: Partial<StoredCampaign> }) {
  const cur = getCurrent()!;
  // concept ids repeat between campaigns ("before-after"), so a slow edit must not land on the campaign that replaced its own
  if (cur.id !== campaignId) throw new Error(REPLACED);
  const now = new Date().toISOString();
  const history = { ...(cur.bannerHistory ?? {}) };
  const updatedAt = { ...(cur.bannerUpdatedAt ?? {}) };
  let visualKeys = { ...(cur.visualKeys ?? {}) };
  const reworded: string[] = [];
  const concepts = cur.campaign.concepts.map((c) => {
    const n = next.get(c.id);
    if (!n) return c;
    history[c.id] =
      opts.history === "push"
        ? [...(history[c.id] ?? []), { concept: c, visualKeys: overridesOf(cur, c.id) }].slice(-20)
        : (history[c.id] ?? []).slice(0, -1);
    visualKeys = Object.fromEntries(Object.entries(visualKeys).filter(([k]) => !k.startsWith(`${c.id}:`)));
    Object.assign(visualKeys, n.visualKeys);
    updatedAt[c.id] = now;
    if (wordsChanged(c, n.concept)) reworded.push(c.id);
    return n.concept;
  });
  // saved languages re-write just these banners on their next request (and their meaning check is redone)
  const locales = Object.fromEntries(
    Object.entries(cur.locales ?? {}).map(([k, l]) => [k, reworded.length ? { ...l, stale: [...new Set([...(l.stale ?? []), ...reworded])], check: undefined } : l]),
  );
  setCurrent({
    ...cur,
    ...opts.extra,
    campaign: { ...cur.campaign, concepts },
    locales,
    visualKeys,
    bannerHistory: history,
    bannerUpdatedAt: updatedAt,
  });
}

async function edit(cur: StoredCampaign, conceptId: string, instruction: string, live: boolean) {
  const ci = cur.campaign.concepts.findIndex((c) => c.id === conceptId);
  if (ci < 0) throw new Error(`Unknown banner ${conceptId}`);
  const c = cur.campaign.concepts[ci];
  const r = await generate({
    kind: "banner-edit",
    schema: BannerEditSchema,
    system: BANNER_EDIT_SYSTEM,
    user: bannerEditUser({ headline: c.headline, subline: c.subline, cta: c.cta, visualPrompt: c.visualPrompt }, instruction, cur.campaign.brief.audience, ci === 0),
  });
  const e = r.data;
  const imageEdit = e.imageEdit.trim();
  const next: Concept = {
    ...c,
    headline: e.headline,
    subline: e.subline,
    cta: e.cta,
    visualPrompt: imageEdit ? e.visualPrompt : c.visualPrompt,
  };

  // The photo: edit the one on the banner, so the rest of it stays. No photo yet -> generate one from the new description.
  let visualKeys = overridesOf(cur, c.id);
  if (imageEdit) {
    visualKeys = {};
    await Promise.all(
      ASPECTS.map(async (a) => {
        const src = visualKeyFor(cur, c, a);
        visualKeys[`${c.id}:${a}`] = hasImage(src)
          ? (await editImage(src, imageEdit, a, live)).key
          : (await generateImage(next.visualPrompt, a, live)).key;
      }),
    );
  }

  const changed = { words: wordsChanged(c, next), picture: !!imageEdit };
  if (changed.words || changed.picture) saveBanners(cur.id, new Map([[c.id, { concept: next, visualKeys }]]), { history: "push" });
  return { summary: e.summary, changed };
}

async function rewrite(cur: StoredCampaign, instructions: string) {
  const r = await generate({
    kind: "banner-rewrite",
    schema: BannersRewriteSchema,
    system: BANNERS_REWRITE_SYSTEM,
    user: bannersRewriteUser(
      cur.campaign.concepts.map(({ id, headline, subline, cta, visualPrompt }) => ({ id, headline, subline, cta, visualPrompt })),
      instructions,
      cur.campaign.brief.audience,
    ),
  });
  const next = new Map<string, BannerSnapshot>();
  let words = false, picture = false;
  cur.campaign.concepts.forEach((c, i) => {
    const w = r.data.concepts.find((x) => x.id === c.id) ?? r.data.concepts[i];
    if (!w) return;
    const n: Concept = { ...c, headline: w.headline, subline: w.subline, cta: w.cta, visualPrompt: w.visualPrompt };
    const pic = n.visualPrompt !== c.visualPrompt;
    if (!pic && !wordsChanged(c, n)) return;
    words ||= wordsChanged(c, n);
    picture ||= pic;
    // A new description means a new photo (generated by the page); an edited photo of the old one no longer applies.
    next.set(c.id, { concept: n, visualKeys: pic ? {} : overridesOf(cur, c.id) });
  });
  saveBanners(cur.id, next, { history: "push", extra: { bannerInstructions: instructions } });
  return { summary: r.data.summary, changed: { words, picture } };
}

function undo(cur: StoredCampaign, conceptId: string) {
  const prev = cur.bannerHistory?.[conceptId]?.at(-1);
  if (!prev) throw new Error("Nothing to undo for this banner");
  const c = cur.campaign.concepts.find((x) => x.id === conceptId)!;
  saveBanners(cur.id, new Map([[conceptId, prev]]), { history: "pop" });
  return {
    summary: "Back to the previous version.",
    changed: { words: wordsChanged(c, prev.concept), picture: c.visualPrompt !== prev.concept.visualPrompt || JSON.stringify(overridesOf(cur, conceptId)) !== JSON.stringify(prev.visualKeys) },
  };
}

export async function POST(req: Request) {
  const body = (await req.json()) as Body;
  const cur = getCurrent();
  if (!cur) return NextResponse.json({ error: "No campaign yet. Generate one first." }, { status: 400 });
  try {
    let out: { summary: string; changed: { words: boolean; picture: boolean } };
    if (body.action === "edit") {
      if (!body.instruction?.trim()) return NextResponse.json({ error: "Say what to change" }, { status: 400 });
      out = await edit(cur, body.conceptId, body.instruction.trim(), !!body.live);
    } else if (body.action === "rewrite") {
      if (!body.instructions?.trim()) return NextResponse.json({ error: "Write the instructions first" }, { status: 400 });
      out = await rewrite(cur, body.instructions.trim());
    } else if (body.action === "undo") {
      out = undo(cur, body.conceptId);
    } else if (body.action === "art-direction") {
      out = await artDirection(cur);
    } else {
      return NextResponse.json({ error: "Unknown action" }, { status: 400 });
    }
    return NextResponse.json({ ...out, ...(await campaignPayload(getCurrent())) });
  } catch (e) {
    return NextResponse.json({ error: (e as Error).message }, { status: e instanceof LlmUnavailable ? 503 : 502 });
  }
}
